FIELD_NOTES_PARAGRAPHS = [
    "Field notes, day one. We set the marker stones along the north "
    "path before the heat rose and photographed each one against the "
    "survey card, so that anyone repeating the walk can stand where we "
    "stood and see what we saw.",
    "By midday the wind had taken two of the paper markers, which is "
    "itself a finding: paper does not survive this ridge. The stones "
    "stayed. We recorded the loss in the margin rather than tidying it "
    "away, because a clean log that hides its gaps teaches the next "
    "walker the wrong lesson.",
    "Day two begins at the east gate. If the stones have moved, we will "
    "know the path is being used by someone who does not sign the log, "
    "and that too will be recorded exactly as found.",
]


def wrap(paragraphs, width):
    return "\n\n".join(
        textwrap.fill(p, width=width, break_long_words=False,
                      break_on_hyphens=False)
        for p in paragraphs
    ) + "\n"


def build_field_notes(out_root):
    assertions = assertions_for(
        "Synthetic field-notes text for a fictional survey walk; "
        "three short paragraphs, invented for this fixture."
    )
    body_original = wrap(FIELD_NOTES_PARAGRAPHS, 88)
    binding = textasset.payload_hash_text(body_original)
    header = dict(assertions)

    def with_header(body):
        return textasset.render_text_asset(assertions, binding, body)

    steps = [
        {"id": "original", "transform": "create",
         "description": "Original text with the provenance header block, "
                        "bound to the whitespace-normalised body hash.",
         "asset": "step-00-original.txt", "data": with_header(body_original),
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": textasset.payload_hash_text(body_original),
         "expected": all_verified(assertions)},
        {"id": "rewrap", "transform": "re-wrap paragraphs 88 -> 64 columns",
         "description": "Same words, narrower lines. The normalised body "
                        "hash is unchanged, so the header binding still "
                        "verifies — line breaks are not content here.",
         "asset": "step-01-rewrapped.txt",
         "data": with_header(wrap(FIELD_NOTES_PARAGRAPHS, 64)),
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": textasset.payload_hash_text(body_original),
         "expected": all_verified(assertions)},
        {"id": "excerpt", "transform": "excerpt (first paragraph only)",
         "description": "Only the first paragraph was kept; the header "
                        "was copied across unchanged. The assertions are "
                        "present but bound to the full text, so they no "
                        "longer verify against this excerpt.",
         "asset": "step-02-excerpt.txt",
         "data": with_header(wrap(FIELD_NOTES_PARAGRAPHS[:1], 88)),
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": textasset.payload_hash_text(
             wrap(FIELD_NOTES_PARAGRAPHS[:1], 88)),
         "expected": all_unknown(assertions)},
        {"id": "strip-header", "transform": "remove the provenance header",
         "description": "The body alone, exactly as it circulates when "
                        "someone copies the text and leaves the header "
                        "behind. No assertion survives in the asset.",
         "asset": "step-03-stripped.txt",
         "data": wrap(FIELD_NOTES_PARAGRAPHS[:1], 88).encode("utf-8"),
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": textasset.payload_hash_text(
             wrap(FIELD_NOTES_PARAGRAPHS[:1], 88)),
         "expected": all_lost(assertions)},
    ]
    assert header is not None
    return finish_chain(
        out_root, "field-notes", "text",
        "A text chain: header-bound original -> re-wrap -> excerpt with "
        "the original header -> header stripped.",
        steps,
    )


DISCLOSURE_BODY = (
    "Disclosure card. This asset is a synthetic demonstration fixture. "
    "It was generated by a script, depicts no real person, place or "
    "event, and was made only to test whether a disclosure survives "
    "being copied. The disclosure travels in the provenance header of "
    "the original file. A copy of this body text alone does not carry "
    "it, and a reader of the copy has no way to know it ever existed.\n"
)


def build_disclosure_card(out_root):
    assertions = assertions_for(
        "A disclosure card whose whole point is the ai_disclosure "
        "assertion: what happens to it when the file is re-encoded, "
        "and when the body is copied without its header."
    )
    binding = textasset.payload_hash_text(DISCLOSURE_BODY)
    original = textasset.render_text_asset(assertions, binding, DISCLOSURE_BODY)
    crlf = original.replace(b"\n", b"\r\n")
    body_only = DISCLOSURE_BODY.encode("utf-8")
    steps = [
        {"id": "original", "transform": "create",
         "description": "Original card: disclosure and the other "
                        "assertions in the header, bound to the body hash.",
         "asset": "step-00-original.txt", "data": original,
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": binding,
         "expected": all_verified(assertions)},
        {"id": "crlf-re-encode", "transform": "line endings LF -> CRLF",
         "description": "The whole file re-encoded with CRLF line "
                        "endings, as happens when a file passes through "
                        "a Windows editor. Normalised content is "
                        "identical; the binding still verifies.",
         "asset": "step-01-crlf.txt", "data": crlf,
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": binding,
         "expected": all_verified(assertions)},
        {"id": "body-only-copy", "transform": "copy the body, drop the header",
         "description": "The body text copied on its own — the most "
                        "common real-world transformation of all. The "
                        "disclosure is lost, silently: nothing in the "
                        "copy says anything is missing.",
         "asset": "step-02-body-only.txt", "data": body_only,
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": binding,
         "expected": all_lost(assertions)},
    ]
    return finish_chain(
        out_root, "disclosure-card", "text",
        "A disclosure chain: original -> CRLF re-encode -> body-only "
        "copy with the disclosure left behind.",
        steps,
    )


BUILDERS = (build_harbour_light, build_field_notes, build_disclosure_card)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    default_root = Path(__file__).resolve().parent.parent / "fixtures" / "v1"
    out_root = Path(argv[0]) if argv else default_root
    out_root.mkdir(parents=True, exist_ok=True)
    for builder in BUILDERS:
        manifest = builder(out_root)
        print("built %s (%d steps)" % (manifest["fixture"], len(manifest["steps"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
