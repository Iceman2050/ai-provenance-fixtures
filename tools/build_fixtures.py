"""Build every fixture deterministically from the recipes in this file.

Run from the repo root:

    python tools/build_fixtures.py [OUTPUT_ROOT]

OUTPUT_ROOT defaults to fixtures/v1. Re-running the generator must
reproduce byte-identical assets and manifests — the test suite checks
this. All content is original synthetic test material written for this
repo; no third-party content is used.
"""

import hashlib
import json
import sys
import textwrap
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from provenance_fixtures import pngio, textasset  # noqa: E402
from provenance_fixtures.checker import record_hash  # noqa: E402

CREATED_AT = "2026-11-13T00:00:00Z"

BASE_ASSERTIONS = [
    ("creator", "Ingenious AI fixture generator (synthetic test asset)"),
    ("created_at", CREATED_AT),
    ("license", "CC0-1.0 -- this test asset only"),
    ("ai_disclosure",
     "Synthetic test asset generated by a script for provenance testing; "
     "it depicts no real person, place or event."),
]


def assertions_for(description):
    return BASE_ASSERTIONS + [("content_description", description)]


def png_text_chunks(assertions, binding):
    chunks = [
        ("provenance.assertion.%s" % assertion_id, value)
        for assertion_id, value in assertions
    ]
    chunks.append(("provenance.payload_sha256", binding))
    return chunks


def sidecar_json(assertions, binding):
    return {
        "assertions": [
            {"id": assertion_id, "value": value}
            for assertion_id, value in assertions
        ],
        "payload_sha256": binding,
    }


def finish_chain(out_root, name, kind, description, raw_steps):
    """Write assets + manifest for one chain.

    raw_steps: list of dicts with id, transform, description, asset
    (filename), data (bytes), sidecar (filename or None), sidecar_data
    (dict or None), payload_sha256, expected (dict id -> status).
    """
    chain_dir = Path(out_root) / name
    chain_dir.mkdir(parents=True, exist_ok=True)
    steps = []
    previous = None
    for index, raw in enumerate(raw_steps):
        (chain_dir / raw["asset"]).write_bytes(raw["data"])
        if raw["sidecar"]:
            (chain_dir / raw["sidecar"]).write_text(
                json.dumps(raw["sidecar_data"], indent=2) + "\n", "utf-8"
            )
        step = {
            "step": index,
            "id": raw["id"],
            "transform": raw["transform"],
            "description": raw["description"],
            "asset": raw["asset"],
            "sidecar": raw["sidecar"],
            "asset_sha256": hashlib.sha256(raw["data"]).hexdigest(),
            "payload_sha256": raw["payload_sha256"],
            "previous_record_sha256": previous,
            "expected": raw["expected"],
        }
        step["record_sha256"] = record_hash(step)
        previous = step["record_sha256"]
        steps.append(step)
    manifest = {
        "fixture": name,
        "version": "v1",
        "asset_kind": kind,
        "description": description,
        "steps": steps,
    }
    (chain_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", "utf-8"
    )
    return manifest


def all_verified(assertions):
    return {assertion_id: "verified" for assertion_id, _v in assertions}


def all_unknown(assertions):
    return {assertion_id: "unknown" for assertion_id, _v in assertions}


def all_lost(assertions):
    return {assertion_id: "lost" for assertion_id, _v in assertions}


# ---------------------------------------------------------------- PNG chain

def harbour_light_pixels(width, height):
    pixels = bytearray()
    for y in range(height):
        for x in range(width):
            r = (x * 5) % 256
            g = (y * 7) % 256
            b = ((x + y) * 3) % 256
            if 30 <= x < 40 and 6 <= y < 14:  # the "beacon" block
                r, g, b = 240, 240, 220
            pixels.extend((r, g, b, 255))
    return bytes(pixels)


def build_harbour_light(out_root):
    assertions = assertions_for(
        "Synthetic 48x32 test pattern: colour gradient with a pale "
        "rectangular beacon block."
    )
    width, height = 48, 32
    pixels = harbour_light_pixels(width, height)
    binding = hashlib.sha256(pixels).hexdigest()

    original = pngio.encode_png(
        width, height, pixels, png_text_chunks(assertions, binding), row_filter=0
    )
    reencoded = pngio.encode_png(
        width, height, pixels, png_text_chunks(assertions, binding), row_filter=1
    )
    stripped = pngio.strip_text_chunks(reencoded)
    small_w, small_h = 24, 16
    small_pixels = pngio.resize_nearest(width, height, pixels, small_w, small_h)
    resized = pngio.encode_png(small_w, small_h, small_pixels, (), row_filter=0)
    crop_w, crop_h, cropped_pixels = pngio.crop_pixels(
        small_w, small_h, small_pixels, (0, 0, 16, 12)
    )
    cropped = pngio.encode_png(crop_w, crop_h, cropped_pixels, (), row_filter=0)

    steps = [
        {"id": "original", "transform": "create",
         "description": "Original asset. Assertions embedded as PNG tEXt "
                        "chunks, bound to the pixel hash.",
         "asset": "step-00-original.png", "data": original,
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": hashlib.sha256(pixels).hexdigest(),
         "expected": all_verified(assertions)},
        {"id": "re-encode", "transform": "re-encode (Sub row filter, same pixels)",
         "description": "Same pixels, different file bytes. The embedded "
                        "assertions survive and their pixel-hash binding "
                        "still matches — file hash changes, content does not.",
         "asset": "step-01-reencode.png", "data": reencoded,
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": hashlib.sha256(pixels).hexdigest(),
         "expected": all_verified(assertions)},
        {"id": "strip-metadata-sidecar", "transform": "strip tEXt chunks; sidecar added",
         "description": "Embedded assertions removed. The same assertions "
                        "travel in a detached sidecar file instead, still "
                        "bound to the unchanged pixel hash.",
         "asset": "step-02-stripped.png", "data": stripped,
         "sidecar": "step-02-sidecar.json",
         "sidecar_data": sidecar_json(assertions, binding),
         "payload_sha256": hashlib.sha256(pixels).hexdigest(),
         "expected": all_verified(assertions)},
        {"id": "resize-sidecar-stale", "transform": "resize 48x32 -> 24x16; sidecar kept",
         "description": "Pixels changed by the resize. The sidecar still "
                        "carries the assertions, but they are bound to the "
                        "old pixel hash — the claims are present and "
                        "unverifiable against this content.",
         "asset": "step-03-resized.png", "data": resized,
         "sidecar": "step-03-sidecar.json",
         "sidecar_data": sidecar_json(assertions, binding),
         "payload_sha256": hashlib.sha256(small_pixels).hexdigest(),
         "expected": all_unknown(assertions)},
        {"id": "crop-no-carriage", "transform": "crop to 16x12; sidecar dropped",
         "description": "Cropped, and nothing carries the assertions any "
                        "more: no embedded metadata, no sidecar. Whatever "
                        "the original claimed is simply gone from the asset.",
         "asset": "step-04-cropped.png", "data": cropped,
         "sidecar": None, "sidecar_data": None,
         "payload_sha256": hashlib.sha256(cropped_pixels).hexdigest(),
         "expected": all_lost(assertions)},
    ]
    return finish_chain(
        out_root, "harbour-light", "png",
        "An image chain: embedded assertions -> re-encode -> metadata "
        "stripped with a sidecar -> resize with a stale sidecar -> crop "
        "with no carriage at all.",
        steps,
    )


